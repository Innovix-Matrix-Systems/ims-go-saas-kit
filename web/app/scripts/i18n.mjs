// The app's translation tooling (no dependencies).
//
//   node scripts/i18n.mjs types [--check]   write src/i18n/messages.gen.ts from the English catalogs
//                                           (the MessageKey union and each key's placeholders);
//                                           --check fails when the file is out of date (CI)
//   node scripts/i18n.mjs check             every language in src/i18n/languages.json has every
//                                           key, the same placeholders and its CLDR plural forms;
//                                           keys stay in their namespace; overrides only replace
//                                           existing keys; no source file names a language code
//   node scripts/i18n.mjs missing <code>    the keys a language lacks, with the English text (JSON)
//
// Catalogs: src/i18n/catalogs/<namespace>/<code>.json. A value is a string or an object of
// plural forms ({"one": "…", "other": "…"}) selected by the {count} variable. A key ending in
// "._context" is a note for translators.
import { readdirSync, readFileSync, writeFileSync, existsSync, statSync } from 'node:fs'
import { join, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const i18nDir = join(root, 'src', 'i18n')
const catalogsDir = join(i18nDir, 'catalogs')
const overridesDir = join(i18nDir, 'overrides')
const typesFile = join(i18nDir, 'messages.gen.ts')
const reference = 'en'
const contextSuffix = '._context'
const pluralForms = ['zero', 'one', 'two', 'few', 'many', 'other']

const languages = JSON.parse(readFileSync(join(i18nDir, 'languages.json'), 'utf8'))

function namespaces(dir) {
  if (!existsSync(dir)) return []
  return readdirSync(dir).filter((name) => statSync(join(dir, name)).isDirectory()).sort()
}

function readCatalog(dir, namespace, code) {
  const file = join(dir, namespace, `${code}.json`)
  if (!existsSync(file)) return null
  return JSON.parse(readFileSync(file, 'utf8'))
}

/** Every language's messages: code -> key -> value (context notes left out). */
function loadAll(dir) {
  const all = {}
  for (const { code } of languages) {
    all[code] = {}
    for (const namespace of namespaces(dir)) {
      const entries = readCatalog(dir, namespace, code) ?? {}
      for (const [key, value] of Object.entries(entries)) {
        if (!key.endsWith(contextSuffix)) all[code][key] = { value, namespace }
      }
    }
  }
  return all
}

const texts = (value) => (typeof value === 'string' ? [value] : Object.values(value))
const placeholders = (value) => [...new Set(texts(value).flatMap((text) => [...text.matchAll(/\{(\w+)\}/g)].map((m) => m[1])))].sort()
const isPlural = (value) => typeof value === 'object' && value !== null

function types() {
  const english = loadAll(catalogsDir)[reference]
  const keys = Object.keys(english).sort()
  const lines = [
    '// Generated by `npm run i18n:types` from src/i18n/catalogs/*/en.json. Do not edit.',
    '',
    '/** Each message key and the names of its {placeholders} (never: none). */',
    'export interface MessageVars {',
  ]
  for (const key of keys) {
    const names = placeholders(english[key].value)
    lines.push(`  '${key}': ${names.length ? names.map((n) => `'${n}'`).join(' | ') : 'never'}`)
  }
  lines.push('}', '', 'export type MessageKey = keyof MessageVars', '')
  return lines.join('\n')
}

function check() {
  const problems = []
  const catalogs = loadAll(catalogsDir)
  const english = catalogs[reference]
  // Keys stay inside their namespace folder.
  for (const [code, entries] of Object.entries(catalogs)) {
    for (const [key, { namespace }] of Object.entries(entries)) {
      if (!key.startsWith(namespace + '.')) problems.push(`${code}: ${key} is in catalogs/${namespace}/ but outside the namespace`)
    }
  }
  for (const lang of languages) {
    if (lang.code === reference) continue
    const own = catalogs[lang.code]
    const required = new Intl.PluralRules(lang.intl).resolvedOptions().pluralCategories
    for (const [key, { value }] of Object.entries(english)) {
      if (!(key in own)) {
        problems.push(`${lang.code}: missing ${key}`)
        continue
      }
      const translated = own[key].value
      const want = placeholders(value).join(', ')
      const got = placeholders(translated).join(', ')
      if (want !== got) problems.push(`${lang.code}: ${key}: placeholders differ (want ${want || 'none'}, got ${got || 'none'})`)
      if (isPlural(value)) {
        if (!isPlural(translated)) problems.push(`${lang.code}: ${key}: must be plural forms like the English text`)
        else {
          const absent = required.filter((form) => !translated[form])
          if (absent.length) problems.push(`${lang.code}: ${key}: plural forms missing: ${absent.join(', ')}`)
        }
      }
      if (isPlural(translated) && Object.keys(translated).some((form) => !pluralForms.includes(form))) {
        problems.push(`${lang.code}: ${key}: unknown plural form (use ${pluralForms.join(', ')})`)
      }
    }
    for (const key of Object.keys(own)) {
      if (!(key in english)) problems.push(`${lang.code}: extra ${key} (not in English)`)
    }
  }
  // Overrides change existing text only.
  const overrides = loadAll(overridesDir)
  for (const [code, entries] of Object.entries(overrides)) {
    for (const key of Object.keys(entries)) {
      if (!(key in english)) problems.push(`overrides ${code}: ${key} is not an existing key`)
    }
  }
  // No language code outside the i18n folder: a language is data, not code.
  const codes = languages.map((lang) => lang.code).filter((code) => code !== reference)
  const quoted = new RegExp(`['"\`](${codes.join('|')})['"\`]`)
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const path = join(dir, name)
      if (statSync(path).isDirectory()) {
        if (path !== i18nDir) walk(path)
      } else if (/\.(ts|tsx)$/.test(name) && !name.endsWith('.gen.ts') && !name.endsWith('.d.ts')) {
        readFileSync(path, 'utf8').split('\n').forEach((line, i) => {
          if (quoted.test(line)) problems.push(`${relative(root, path)}:${i + 1} names a language code (read it from src/i18n/languages)`)
        })
      }
    }
  }
  walk(join(root, 'src'))
  // The generated types are current.
  if (!existsSync(typesFile) || readFileSync(typesFile, 'utf8') !== types()) {
    problems.push('src/i18n/messages.gen.ts is out of date: run npm run i18n:types')
  }
  for (const lang of languages) {
    const total = Object.keys(english).length
    const have = Object.keys(catalogs[lang.code]).filter((key) => key in english).length
    console.log(`${lang.code.padEnd(3)} ${lang.english.padEnd(10)} ${have}/${total}${lang.reviewed ? '' : '  (beta)'}`)
  }
  if (problems.length) {
    console.error(problems.join('\n'))
    console.error(`\n${problems.length} problem(s).`)
    process.exit(1)
  }
  console.log('Every language is complete.')
}

function missing(code) {
  const lang = languages.find((l) => l.code === code)
  if (!lang) {
    console.error(`${code} is not in src/i18n/languages.json`)
    process.exit(1)
  }
  const catalogs = loadAll(catalogsDir)
  const notes = {}
  for (const namespace of namespaces(catalogsDir)) {
    for (const [key, value] of Object.entries(readCatalog(catalogsDir, namespace, reference) ?? {})) {
      if (key.endsWith(contextSuffix)) notes[key.slice(0, -contextSuffix.length)] = value
    }
  }
  const keys = Object.entries(catalogs[reference])
    .filter(([key]) => !(key in catalogs[code]))
    .map(([key, { value, namespace }]) => ({ key, namespace, english: value, ...(notes[key] ? { context: notes[key] } : {}) }))
  const forms = new Intl.PluralRules(lang.intl).resolvedOptions().pluralCategories
  console.log(JSON.stringify({ language: lang, plural_forms: forms, keys }, null, 2))
}

const [command, arg] = process.argv.slice(2)
if (command === 'types') {
  const generated = types()
  if (arg === '--check') {
    if (!existsSync(typesFile) || readFileSync(typesFile, 'utf8') !== generated) {
      console.error('src/i18n/messages.gen.ts is out of date: run npm run i18n:types')
      process.exit(1)
    }
  } else {
    writeFileSync(typesFile, generated)
    console.log(`wrote ${relative(root, typesFile)}`)
  }
} else if (command === 'check') {
  check()
} else if (command === 'missing' && arg) {
  missing(arg)
} else {
  console.error('usage: node scripts/i18n.mjs types [--check] | check | missing <code>')
  process.exit(2)
}
